package net.airplus.features.command.commands

import net.airplus.features.command.Command
import net.airplus.utils.movement.MovementUtils.forward

object HClipCommand : Command("hclip") {
    /**
     * Execute commands with provided [args]
     */
    override fun execute(args: Array<String>) {
        if (args.size > 1) {
            try {
                forward(args[1].toDouble())
                chat("You were teleported.")
            } catch (exception: NumberFormatException) {
                chatSyntaxError()
            }
            return
        }

        chatSyntax("hclip <value>")
    }
}